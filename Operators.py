# Operators

# Comparison Operators

a = 10
b = 5

print("A =", a)
print("B =", b)

print(a == b)  # Equal to
print(a != b)  # Not equal to
print(a > b)   # Greater than
print(a < b)   # Less than
print(a >= b)  # Greater than or equal to
print(a <= b)  # Less than or equal to


# Logical Operators

print(a > 0 and b > 0)  # AND
print(a > 0 or b < 0)   # OR
print(not(a > b))      # NOT