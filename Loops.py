# Loops

# For loop

for i in range(1, 11, 2):
    print(i)


# Loops in List

fruits = ["Apple", "Mango", "Banana", "Orange"]

for u in fruits[1:3]:
    print(u)


# Table of 5

for i in range(1, 11):
    print("5 X " + str(i) + " = " + str(i * 5))


# While Loop

i = 1

while i <= 5:
    print(i)
    i = i + 1